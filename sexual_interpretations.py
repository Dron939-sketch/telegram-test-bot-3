def get_temperament_type(scores):
    """
    Определяет тип темперамента по баллам
    scores: dict с баллами для PREDATOR, ARTIST, OBSERVER, PLAYER
    """
    max_type = max(scores, key=scores.get)
    return TEMPERAMENT_TYPES.get(max_type, TEMPERAMENT_TYPES["PREDATOR"])

def get_top_fetishes(scores, top_n=3):
    """
    Возвращает топ-N фетишей по баллам
    scores: dict с баллами для SMELL, MATERIALS, BODY_PARTS, SITUATIONS
    """
    sorted_fetishes = sorted(scores.items(), key=lambda x: x[1], reverse=True)
    top = []
    for fetish_code, score in sorted_fetishes[:top_n]:
        if score > 0:
            fetish = FETISH_TYPES.get(fetish_code)
            if fetish:
                top.append({
                    "code": fetish_code,
                    "name": fetish["name"],
                    "emoji": fetish["emoji"],
                    "description": fetish["description"],
                    "manifestations": fetish["manifestations"],
                    "try": fetish["try"],
                    "score": score
                })
    return top

def get_format_readiness(scores):
    """
    Определяет готовность к форматам
    scores: dict с баллами для каждого формата
    """
    ready = []
    interested = []
    not_interested = []
    
    for format_code, score in scores.items():
        format_info = FORMATS.get(format_code)
        if not format_info:
            continue
            
        if score >= 8:
            ready.append({
                "code": format_code,
                "name": format_info["name"],
                "emoji": format_info["emoji"],
                "desc": format_info["desc"]
            })
        elif score >= 4:
            interested.append({
                "code": format_code,
                "name": format_info["name"],
                "emoji": format_info["emoji"],
                "desc": format_info["desc"]
            })
        else:
            not_interested.append({
                "code": format_code,
                "name": format_info["name"],
                "emoji": format_info["emoji"],
                "desc": format_info["desc"]
            })
    
    return {
        "ready": ready,
        "interested": interested,
        "not_interested": not_interested
    }

