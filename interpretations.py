# ==================== ОСНОВНАЯ ФУНКЦИЯ ПОЛУЧЕНИЯ ИНТЕРПРЕТАЦИИ ====================

def get_interpretation(gender, narrative, level, age, second_narrative=None, third_narrative=None):
    """
    Возвращает полную интерпретацию для пользователя с подстановкой возраста
    Поддерживает одиночные, двойные и тройные нарративы
    """
    age_1 = age + 1
    age_5 = age + 5
    age_10 = age + 10
    
    # Выбираем базовую интерпретацию
    if gender == "М":
        base_text = MALE_INTERPRETATIONS[narrative][level]
    else:
        base_text = FEMALE_INTERPRETATIONS[narrative][level]
    
    # Подставляем возраст
    base_text = base_text.replace("{age}", str(age))
    base_text = base_text.replace("{age_1}", str(age_1))
    base_text = base_text.replace("{age_5}", str(age_5))
    base_text = base_text.replace("{age_10}", str(age_10))
    
    result = base_text
    
    # Добавляем интерпретацию для двойного нарратива
    if second_narrative and not third_narrative:
        key = (gender, narrative, second_narrative)
        if key in DUAL_NARRATIVE_INTERPRETATIONS:
            result += DUAL_NARRATIVE_INTERPRETATIONS[key]
        else:
            # Универсальная интерпретация для двойного нарратива
            result += f"""
────────────────────
*ТЫ В ДВУХ МИРАХ*
────────────────────

Твой основной мир — *{NARRATIVE_NAMES[narrative]}*. Это твоя цель, твоя суть, то, кем ты хочешь быть.

А мир *{NARRATIVE_NAMES[second_narrative]}* — это твоё средство. Ты используешь его инструменты, чтобы достичь цели в основном мире.

Жить в двух мирах сложно. Приходится жонглировать разными ценностями, разными ролями, разными правилами. Но это и даёт преимущество — ты видишь то, чего не видят другие.
"""
    
    # Добавляем интерпретацию для тройного нарратива
    elif second_narrative and third_narrative:
        key = (gender, narrative, second_narrative, third_narrative)
        if key in TRIPLE_NARRATIVE_INTERPRETATIONS:
            result += TRIPLE_NARRATIVE_INTERPRETATIONS[key]
        else:
            # Универсальная интерпретация для тройного нарратива
            result += f"""
────────────────────
*ТЫ В ТРЁХ МИРАХ*
────────────────────

Твой основной мир — *{NARRATIVE_NAMES[narrative]}*. Это твоя цель.

Миры *{NARRATIVE_NAMES[second_narrative]}* и *{NARRATIVE_NAMES[third_narrative]}* — твои средства. Ты используешь их инструменты, чтобы достичь цели.

Ты — человек трёх миров. Это невероятно сложно. Ты постоянно переключаешься между разными ролями, разными правилами, разными людьми. Ты устаёшь, но не можешь остановиться.

Это твой путь. Это твоя ноша. И только тебе решать, нести её дальше или выбрать что-то одно.
"""
    
    return result
