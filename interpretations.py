# ==================== ФУНКЦИЯ ПОЛУЧЕНИЯ ИНТЕРПРЕТАЦИИ ====================

def get_interpretation(gender, narrative, level, age, second_narrative=None):
    """
    Возвращает полную интерпретацию для пользователя с подстановкой возраста
    """
    age_1 = age + 1
    age_5 = age + 5
    age_10 = age + 10
    
    if gender == "М":
        base_text = MALE_INTERPRETATIONS[narrative][level]
    else:
        base_text = FEMALE_INTERPRETATIONS[narrative][level]
    
    # Подставляем возраст
    base_text = base_text.replace("{age}", str(age))
    base_text = base_text.replace("{age_1}", str(age_1))
    base_text = base_text.replace("{age_5}", str(age_5))
    base_text = base_text.replace("{age_10}", str(age_10))
    
    if second_narrative:
        second_text = f"\n\n────────────────────\n"
        second_text += f"*ТЫ В ДВУХ МИРАХ*\n"
        second_text += f"────────────────────\n\n"
        second_text += f"Твой основной мир — *{NARRATIVE_NAMES[narrative]}*. Это твоя цель, твоя суть, то, кем ты хочешь быть.\n\n"
        second_text += f"А мир *{NARRATIVE_NAMES[second_narrative]}* — это твоё средство. Ты используешь его инструменты, чтобы достичь цели.\n\n"
        
        if narrative == "ЧВ" and second_narrative == "СБ":
            second_text += "Ты хочешь внимания, но добиваешься его через силу и власть. Ты становишься медийным лицом в силовых структурах, блогером-патриоткой. Ты используешь связи, чтобы пробиться."
        elif narrative == "ЧВ" and second_narrative == "ТФ":
            second_text += "Ты хочешь славы, но работаешь для этого как лошадь. Твой успех — это результат труда, репетиций, вложений. Ты не ждёшь чуда, ты его создаёшь."
        elif narrative == "ЧВ" and second_narrative == "УБ":
            second_text += "Ты привлекаешь внимание глубиной. Ты становишься интеллектуальным блогером, экспертом в СМИ, той, кого цитируют. Твой ум — твой главный капитал."
        
        elif narrative == "СБ" and second_narrative == "ЧВ":
            second_text += "Ты рвёшься к власти, но используешь для этого внимание и связи. Ты становишься публичной фигурой, и это открывает тебе двери в кабинеты."
        elif narrative == "СБ" and second_narrative == "ТФ":
            second_text += "Ты хочешь власти, но добиваешься её через труд. Ты работаешь так много, что тебя начинают уважать. Ты не лезешь в криминал, ты просто лучшая в своём деле."
        elif narrative == "СБ" and second_narrative == "УБ":
            second_text += "Ты хочешь влияния, но получаешь его через знания. Ты становишься экспертом, без которого не могут обойтись. Твой ум даёт тебе власть."
        
        elif narrative == "ТФ" and second_narrative == "СБ":
            second_text += "Ты хочешь зарабатывать, но используешь для этого связи и силу. Ты решаешь вопросы через знакомства, твой бизнес держится на авторитете."
        elif narrative == "ТФ" and second_narrative == "ЧВ":
            second_text += "Ты строишь бизнес на внимании. Твой доход — от рекламы, блогов, инфлюенса. Ты монетизируешь популярность."
        elif narrative == "ТФ" and second_narrative == "УБ":
            second_text += "Твой бизнес — на знаниях. Ты продаёшь не товары, а экспертизу. Ты — консультант, тренер, наставник."
        
        elif narrative == "УБ" and second_narrative == "ЧВ":
            second_text += "Ты мыслишь глубоко, но продвигаешь идеи через внимание. Ты — публичный интеллектуал, твои книги становятся бестселлерами."
        elif narrative == "УБ" and second_narrative == "СБ":
            second_text += "Ты познаёшь мир, но используешь власть. Ты становишься тем, чьё слово — закон в научной среде. Ты управляешь институтами."
        elif narrative == "УБ" and second_narrative == "ТФ":
            second_text += "Ты создаёшь знания, но применяешь их на практике. Ты — прикладной учёный, инженер, изобретатель, который внедряет свои идеи."
        
        second_text += f"\n\nЖить в двух мирах сложно. Приходится жонглировать разными ценностями, разными ролями, разными правилами. Но это и даёт преимущество — ты видишь то, чего не видят другие."
        
        return base_text + second_text
    
    return base_text
