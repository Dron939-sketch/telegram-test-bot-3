# ==================== ОСНОВНАЯ ФУНКЦИЯ ПОЛУЧЕНИЯ ИНТЕРПРЕТАЦИИ ====================

def get_interpretation(gender, narrative, level, age, second_narrative=None, third_narrative=None):
    """
    Возвращает полную интерпретацию для пользователя с подстановкой возраста
    Поддерживает одиночные, двойные и тройные нарративы
    """
    age_1 = age + 1
    age_5 = age + 5
    age_10 = age + 10
    
    # Выбираем базовую интерпретацию
    try:
        if gender == "М":
            base_text = MALE_INTERPRETATIONS[narrative][level]
        else:
            base_text = FEMALE_INTERPRETATIONS[narrative][level]
    except KeyError:
        # Заглушка на случай отсутствия интерпретации
        base_text = f"""
*ТВОЙ МИР:* {NARRATIVE_NAMES.get(narrative, "НЕИЗВЕСТНЫЙ")}
*ТВОЯ РОЛЬ:* Уровень {level}

────────────────────
ПРОШЛОЕ
────────────────────

Твой путь только начинается. В прошлом ты был тем, кем тебя сделали обстоятельства.

────────────────────
НАСТОЯЩЕЕ
────────────────────

Сегодня тебе {age}. Ты в поиске себя, в поиске своего пути.

────────────────────
ТВОИ ТАЙНЫЕ ЖЕЛАНИЯ
────────────────────

Ты хочешь признания. Хочешь любви — настоящей, глубокой, на всю жизнь.

────────────────────
БУДУЩЕЕ
────────────────────

*Через год, в {age_1}:*

Ты сделаешь первые шаги к своей цели.

*Через 5 лет, в {age_5}:*

Ты либо добьешься успеха, либо поймешь, что выбрал не тот путь.

*Через 10 лет, в {age_10}:*

Ты оглянешься назад и поймешь, что все было не зря.

────────────────────
ТВОЙ ВЫБОР

Судьба не предопределена. Всё в твоих руках.
"""
    
    # Подставляем возраст
    base_text = base_text.replace("{age}", str(age))
    base_text = base_text.replace("{age_1}", str(age_1))
    base_text = base_text.replace("{age_5}", str(age_5))
    base_text = base_text.replace("{age_10}", str(age_10))
    
    result = base_text
    
    # Добавляем интерпретацию для двойного нарратива
    if second_narrative and not third_narrative:
        # Сначала проверяем в женских двойных
        if gender == "Ж":
            key = (gender, narrative, second_narrative)
            if key in DUAL_NARRATIVE_INTERPRETATIONS:
                dual_text = DUAL_NARRATIVE_INTERPRETATIONS[key]
                dual_text = dual_text.replace("{age}", str(age))
                dual_text = dual_text.replace("{age_1}", str(age_1))
                dual_text = dual_text.replace("{age_5}", str(age_5))
                dual_text = dual_text.replace("{age_10}", str(age_10))
                result += dual_text
        # Для мужчин
        else:
            key = (gender, narrative, second_narrative)
            if key in MALE_DUAL_NARRATIVE_INTERPRETATIONS:
                dual_text = MALE_DUAL_NARRATIVE_INTERPRETATIONS[key]
                dual_text = dual_text.replace("{age}", str(age))
                dual_text = dual_text.replace("{age_1}", str(age_1))
                dual_text = dual_text.replace("{age_5}", str(age_5))
                dual_text = dual_text.replace("{age_10}", str(age_10))
                result += dual_text
    
    # Добавляем интерпретацию для тройного нарратива
    elif second_narrative and third_narrative:
        key = (gender, narrative, second_narrative, third_narrative)
        if key in TRIPLE_NARRATIVE_INTERPRETATIONS:
            triple_text = TRIPLE_NARRATIVE_INTERPRETATIONS[key]
            triple_text = triple_text.replace("{age}", str(age))
            triple_text = triple_text.replace("{age_1}", str(age_1))
            triple_text = triple_text.replace("{age_5}", str(age_5))
            triple_text = triple_text.replace("{age_10}", str(age_10))
            result += triple_text
    
    return result
