def analyze_interactions(cocktail: Dict[str, int]) -> Dict:
    conflicts = [
        r for r in INTERACTION_RULES["conflicts"]
        if r["cond"](cocktail)
    ]
    synergies = [
        r for r in INTERACTION_RULES["synergies"]
        if r["cond"](cocktail)
    ]
    return {"conflicts": conflicts, "synergies": synergies}


