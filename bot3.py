async def handle_voice_message(message: types.Message):
    """Обработчик голосовых сообщений"""
    user_id = message.from_user.id
    user = user_data.get(user_id)
    
    if not user:
        await message.answer("Начни с /start", reply_markup=InlineKeyboardMarkup(inline_keyboard=[
            [InlineKeyboardButton(text="🏠 Меню", callback_data="back_to_start")]
        ]))
        return
    
    # Проверяем, прошел ли тест
    if user.get("conversation_state") != RESULTS and not user.get("final_profile"):
        await message.answer(
            "🎙 *Голосовые сообщения доступны только после завершения теста*\n\n"
            "Сначала пройди 4 этапа, чтобы я мог анализировать твои вопросы с учетом профиля.",
            parse_mode="Markdown",
            reply_markup=InlineKeyboardMarkup(inline_keyboard=[
                [InlineKeyboardButton(text="🚀 Пройти тест", callback_data="start_test")],
                [InlineKeyboardButton(text="🏠 В меню", callback_data="back_to_start")]
            ])
        )
        return
    
    status_msg = await message.answer("🎤 *Распознаю речь...*", parse_mode="Markdown")
    
    temp_file = None
    try:
        file_info = await message.bot.get_file(message.voice.file_id)
        
        with tempfile.NamedTemporaryFile(delete=False, suffix='.ogg') as tmp:
            temp_file = tmp.name
            await message.bot.download_file(file_info.file_path, destination=temp_file)
        
        recognized_text = await speech_to_text(temp_file)
        
        try:
            os.unlink(temp_file)
        except:
            pass
        
        if not recognized_text:
            await status_msg.edit_text(
                "❌ *Не удалось распознать речь*\n\n"
                "Попробуй еще раз или напиши текстом.",
                parse_mode="Markdown"
            )
            return
        
        await status_msg.edit_text(
            f"📝 *Ты сказал:*\n"
            f"_{recognized_text}_\n\n"
            f"🤔 *Думаю над ответом...*",
            parse_mode="Markdown"
        )
        
        # Получаем профиль и контекст
        profile = user.get("final_profile", {})
        model_data = user.get("confinement_model")
        model = ConfinementModel9.from_dict(model_data) if model_data else None
        context = user_contexts.get(user_id)
        mode = context.communication_mode if context else "medium"
        
        mode_prompt = COMMUNICATION_MODES.get(mode, COMMUNICATION_MODES["medium"])["prompt"]
        
        profile_text = f"Стратегии: СБ-{profile.get('strategies', {}).get('СБ', 3)}/6, ТФ-{profile.get('strategies', {}).get('ТФ', 3)}/6, УБ-{profile.get('strategies', {}).get('УБ', 3)}/6, ЧВ-{profile.get('strategies', {}).get('ЧВ', 3)}/6"
        
        confinement_text = ""
        if model and model.key_confinement:
            elem = model.key_confinement['element']
            confinement_text = f"Ключевое ограничение: {elem.name}"
        
        prompt = f"""Вопрос: {recognized_text}

ПРОФИЛЬ ПОЛЬЗОВАТЕЛЯ:
{profile_text}
{confinement_text}

СТИЛЬ: {mode_prompt}

Дай короткий, практичный ответ, 2-4 предложения, с учетом профиля. Отвечай от имени Шнура."""
        
        response = await call_deepseek(prompt, max_tokens=300)
        
        if not response:
            response = f"Слушай, я вижу твой профиль. С такими вводными я бы посоветовал не торопиться и сделать маленький шаг сегодня."
        
        keyboard = InlineKeyboardMarkup(inline_keyboard=[
            [InlineKeyboardButton(text="❓ Ещё вопрос", callback_data="show_help")],
            [InlineKeyboardButton(text="🧠 К портрету", callback_data="show_results")]
        ])
        
        await status_msg.edit_text(
            f"📝 *Ты сказал:*\n_{recognized_text}_\n\n"
            f"*Ответ Шнура:*\n{response}",
            parse_mode="Markdown",
            reply_markup=keyboard
        )
        
        audio_data = await text_to_speech(response, mode)
        if audio_data:
            audio_file = BufferedInputFile(audio_data, filename="response.ogg")
            await message.answer_voice(
                audio_file,
                caption="🎙 *Голосовой ответ от Шнура*",
                parse_mode="Markdown"
            )
    
    except Exception as e:
        logger.error(f"Ошибка при обработке голосового сообщения: {e}", exc_info=True)
        await status_msg.edit_text(
            "❌ *Произошла ошибка*\n\n"
            "Попробуй еще раз или напиши текстом.",
            parse_mode="Markdown"
        )

