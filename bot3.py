async def send_question(user_id: int, state: FSMContext):
    data = await state.get_data()
    qi: int = data.get("qi", 0)

    if qi >= len(QUESTIONS):
        await show_result(user_id, state)
        return

    q = QUESTIONS[qi]
    cat = q["cat"]
    lvl = q["level"]
    qtype = q["type"]
    cat_icon = MATRIX[cat]["icon"]
    cat_label = MATRIX[cat]["label"]

    # Определяем секцию теста
    section_labels = {"A": "поведение", "B": "ситуация", "C": "ценности"}
    section = section_labels.get(qtype, "")

    # Прогресс
    prog = progress(qi + 1, len(QUESTIONS))
    pct = round((qi + 1) / len(QUESTIONS) * 100)

    # Удаляем предыдущее сообщение
    prev_id = data.get("last_msg_id")
    if prev_id:
        try:
            await bot.delete_message(user_id, prev_id)
        except Exception:
            pass

    # Текст вопроса
    strat_name = MATRIX[cat][lvl]["name"]
    text = (
        f"{cat_icon} <b>{cat_label}  ·  {strat_name}</b>  "
        f"<i>[{section}]</i>\n"
        f"<code>{prog}</code> {pct}%  "
        f"<i>вопрос {qi + 1} из {len(QUESTIONS)}</i>\n"
        f"{'─' * 28}\n\n"
        f"{q['text']}"
    )

    builder = InlineKeyboardBuilder()
    for key, label in SCALE.items():
        builder.button(text=label, callback_data=f"a|{qi}|{key}")
    builder.adjust(2)

    sent = await bot.send_message(user_id, text, reply_markup=builder.as_markup())
    await state.update_data(last_msg_id=sent.message_id)


