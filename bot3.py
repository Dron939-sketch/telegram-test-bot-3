    """Даёт название комбинации (для интереса)"""
    
    sb = cocktail["СБ"]
    tf = cocktail["ТФ"]
    ub = cocktail["УБ"]
    chv = cocktail["ЧВ"]
    
    # Базовые архетипы
    if sb == 6 and tf >= 4 and ub >= 4 and chv <= 3:
        return "⚔️ ЗАВОЕВАТЕЛЬ"
    if sb <= 2 and tf <= 2 and ub <= 2 and chv <= 2:
        return "🐣 РЕБЁНОК"
