async def callback_handler(callback: types.CallbackQuery):
    """Обработчик всех callback-запросов"""
    user_id = callback.from_user.id
    data = callback.data
    
    log_debug(f"📞 callback_handler: {data}", user_id)
    
    # Получаем данные пользователя
    context = user_data.get(user_id, {})
    
    # Режимы
    if data == "mode_hard":
        return await mode_callback(callback, "hard")
    elif data == "mode_medium":
        return await mode_callback(callback, "medium")
    elif data == "mode_soft":
        return await mode_callback(callback, "soft")
    
    # Навигация
    elif data == "start_test":
        return await start_test(callback)
    elif data == "why_details":
        return await why_details(callback)
    elif data == "back_to_start":
        return await back_to_start(callback)
    
    # Этап 1
    elif data == "stage1_details":
        return await show_stage_1_details(callback, context)
    elif data == "back_to_stage1_intro":
        return await back_to_stage1_intro(callback, context)
    elif data == "start_stage_1":
        return await start_stage_1(callback, context)
    elif data.startswith("stage1_"):
        return await handle_stage_1_answer(callback, context)
    
    # Этап 2
    elif data == "show_stage_2_intro":
        return await show_stage_2_intro(callback, context)
    elif data == "stage2_details":
        return await show_stage_2_details(callback, context)
    elif data == "back_to_stage2_intro":
        return await back_to_stage2_intro(callback, context)
    elif data == "start_stage_2":
        return await start_stage_2(callback, context)
    elif data.startswith("stage2_"):
        return await handle_stage_2_answer(callback, context)
    
    # Этап 3
    elif data == "show_stage_3_intro":
        return await show_stage_3_intro(callback, context)
    elif data == "stage3_details":
        return await show_stage_3_details(callback, context)
    elif data == "back_to_stage3_intro":
        return await back_to_stage3_intro(callback, context)
    elif data == "start_stage_3":
        return await start_stage_3(callback, context)
    elif data.startswith("stage3_"):
        return await handle_stage_3_answer(callback, context)
    
    # Этап 4
    elif data == "show_stage_4_intro":
        return await show_stage_4_intro(callback, context)
    elif data == "stage4_details":
        return await show_stage_4_details(callback, context)
    elif data == "back_to_stage4_intro":
        return await back_to_stage4_intro(callback, context)
    elif data == "start_stage_4":
        return await start_stage_4(callback, context)
    elif data.startswith("stage4_"):
        return await handle_stage_4_answer(callback, context)
    
    # Результаты и помощь
    elif data == "show_results":
        return await show_results_screen(callback, context)
    elif data == "show_help":
        keyboard = get_help_keyboard()
        await callback.message.edit_text(
            "🎯 *ЧЕМ Я МОГУ БЫТЬ ПОЛЕЗЕН*\n\n"
            "Выбери категорию или напиши сам:",
            reply_markup=keyboard,
            parse_mode="Markdown"
        )
    elif data == "ask_question":
        await ask_question(callback, context)
    
    # Категории помощи
    elif data.startswith("help_"):
        category = data.replace("help_", "")
        await show_help_category(callback, context, category)
    
    # Вопросы из категорий
    elif data.startswith("ask_cat_"):
        parts = data.split("_")
        if len(parts) >= 4:
            category = parts[2]
            idx = int(parts[3])
            await handle_category_question(callback, context, category, idx)

