        # 2. Поведение (из профилей)
        self._build_behavior()
        
        # 3. Способности (из уровней)
        self._build_capabilities()
        
        # 4. Убеждения (из архетипов)
        self._build_beliefs()
        
        # 5. Системы (выводим из контекста)
        self._build_systems()
        
        # 6. Идентичность (синтез)
        self._build_identity()
        
