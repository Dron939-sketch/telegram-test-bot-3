def bar(value: float, max_v: float = 6.0, length: int = 8) -> str:
    filled = round((value / max_v) * length)
    return "█" * filled + "░" * (length - filled)

def progress(current: int, total: int, length: int = 12) -> str:
    filled = round((current / total) * length)
    return "▓" * filled + "░" * (length - filled)

def divider(char: str = "─", length: int = 32) -> str:
    return char * length

