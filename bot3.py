    print("📊 Команды: /stats, /apistatus, /test_yandex, /test_mot")
    print("🎙 Голос: " + ("✅" if YANDEX_API_KEY and DEEPGRAM_API_KEY else "❌"))
    print("🧠 Конфайнмент-моделирование: ✅")
    print("🌍 Анализ среды: ✅")
    print("🛠 Пути развития: ✅")
    print("="*50 + "\n")
    
    await dp.start_polling(bot, drop_pending_updates=True)


