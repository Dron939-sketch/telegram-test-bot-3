def level(score):
    """Дробный балл → целый уровень"""
    return max(1, min(6, round(score)))

def get_profile_text(scores):
    """Формирует текст профиля как в консольной версии"""
    text = "📊 *ВАШ ПРОФИЛЬ*\n\n"
    
    for key, score in scores.items():
        vec = VECTORS[key]
        lvl = level(score)
        info = vec["levels"][lvl]
        
        filled = "█" * lvl
        empty = "░" * (6 - lvl)
        bar = filled + empty
        
        text += f"*{key}* `[{bar}]` {score:.1f}/6\n"
        text += f"_{vec['name']}_: *{info['name']}* — {info['action']}\n"
        text += f"└ {info['desc']}\n\n"
    
    sb = level(scores["СБ"])
    tf = level(scores["ТФ"])
    ub = level(scores["УБ"])
    cv = level(scores["ЧВ"])
    
    text += f"─────────────────────\n"
    text += f"*Профиль:* СБ-{sb} ТФ-{tf} УБ-{ub} ЧВ-{cv}\n"
    
    return text

def get_priority_order(scores: dict) -> list:
    """Определяет порядок приоритетов как в консольной версии"""
    tf = level(scores["ТФ"])
    
    if tf <= 2:
        rest = sorted([(k, v) for k, v in scores.items() if k != "ТФ"], key=lambda x: x[1])
        return ["ТФ"] + [r[0] for r in rest]
    else:
        return [k for k, _ in sorted(scores.items(), key=lambda x: x[1])]

def call_deepseek(prompt, system_message=""):
    """Вызов DeepSeek API"""
    if not DEEPSEEK_API_KEY:
        return None
    
    try:
        headers = {
            "Authorization": f"Bearer {DEEPSEEK_API_KEY}",
            "Content-Type": "application/json"
        }
        
        messages = []
        if system_message:
            messages.append({"role": "system", "content": system_message})
        messages.append({"role": "user", "content": prompt})
        
        data = {
            "model": "deepseek-chat",
            "messages": messages,
            "temperature": 0.7,
            "max_tokens": 2000,
        }
        
        response = requests.post(
            "https://api.deepseek.com/v1/chat/completions",
            headers=headers,
            json=data,
            timeout=60
        )
        
        if response.status_code == 200:
            return response.json()["choices"][0]["message"]["content"]
        else:
            logger.error(f"API Error: {response.status_code}")
            return None
            
    except Exception as e:
        logger.error(f"DeepSeek API error: {e}")
        return None

