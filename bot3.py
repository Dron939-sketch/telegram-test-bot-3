def calculate_thinking_level_by_scores(level_scores: dict) -> int:
    """Вычисляет уровень мышления по набранным баллам"""
    total_score = 0
    total_questions = 0
    
    for level, score in level_scores.items():
        total_score += score * int(level)
        total_questions += score
    
    if total_questions == 0:
        return 5
    
    return round(total_score / total_questions)

def get_level_group(level: int) -> str:
    """Возвращает группу уровня"""
    if level <= 3:
        return "1-3"
    elif level <= 6:
        return "4-6"
    else:
        return "7-9"

def need_clarification_stage2(level_scores: dict) -> bool:
    """Проверяет, нужны ли уточняющие вопросы для этапа 2"""
    high_levels = sum(1 for score in level_scores.values() if score > 2)
    return high_levels > 2

