        if self.chv >= 5 and self.sb <= 2:
            imbalances.append({
                "type": "🔄 ПЕРЕКОС В ОТНОШЕНИЯ",
                "desc": "Вы сильны в отношениях, но слабы в защите. Можете страдать от эксплуатации."
            })
        
        return imbalances
    
