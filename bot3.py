# ✅ НОВАЯ ФУНКЦИЯ ПЕРЕСЧЁТА (1..4 → 1..6)
def level(score):
    """
    Дробный балл 1..4 → целый уровень 1..6
    
    Таблица преобразования:
    1.00 - 1.49  →  1
    1.50 - 2.00  →  2
    2.01 - 2.50  →  3
    2.51 - 3.00  →  4
    3.01 - 3.50  →  5
    3.51 - 4.00  →  6
    """
    if score <= 1.49:
        return 1
    elif score <= 2.00:
        return 2
    elif score <= 2.50:
        return 3
    elif score <= 3.00:
        return 4
    elif score <= 3.50:
        return 5
    else:
        return 6

def get_profile_text(scores):
    """Формирует текст профиля с эмодзи и без аббревиатур"""
    text = "📊 *ВАШ ПРОФИЛЬ*\n\n"
    
    for key, score in scores.items():
        vec = VECTORS[key]
        lvl = level(score)
        info = vec["levels"][lvl]
        
        filled = "█" * lvl
        empty = "░" * (6 - lvl)
        bar = filled + empty
        
        text += f"{vec['emoji']} *{vec['name']}*\n"
        text += f"`[{bar}]` {lvl}/6 — *{info['name']}*\n"
        text += f"└ {info['desc']}\n\n"
    
    text += f"═══════════════════════\n"
    
    return text

def get_priority_order(scores: dict) -> list:
    """Определяет порядок приоритетов"""
    tf = level(scores["ТФ"])
    
    if tf <= 2:
        rest = sorted([(k, v) for k, v in scores.items() if k != "ТФ"], key=lambda x: x[1])
        return ["ТФ"] + [r[0] for r in rest]
    else:
        return [k for k, _ in sorted(scores.items(), key=lambda x: x[1])]

