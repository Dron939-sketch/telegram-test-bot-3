class MiltonModel:
    """Язык неопределенности для работы с бессознательным"""
    
    nominalizations = [
        "понимание", "осознание", "отношение", "уважение", "доверие",
        "свобода", "независимость", "безопасность", "уверенность", "спокойствие",
        "развитие", "рост", "изменение", "трансформация", "исцеление",
        "любовь", "счастье", "радость", "удовольствие", "гармония",
        "сила", "мудрость", "опыт", "знание", "интуиция"
    ]
    
    vague_verbs = [
        "сделать", "почувствовать", "понять", "осознать", "изменить",
        "двигаться", "развиваться", "расти", "меняться", "трансформироваться",
        "открыть", "обнаружить", "найти", "увидеть", "услышать",
        "довериться", "расслабиться", "отпустить", "принять", "позволить"
    ]
    
    vague_nouns = [
        "человек", "люди", "некто", "кто-то", "каждый",
        "некоторые", "многие", "большинство", "окружающие", "другие"
    ]
    
    deletions = [
        "Можно...", "Хочется...", "Бывает...", "Случается...", 
        "Иногда...", "Порой...", "Бывало...", "Может быть..."
    ]
    
    unspecific_nouns = [
        "это", "то", "нечто", "что-то", "все это",
        "такое", "эта ситуация", "это состояние", "это чувство"
    ]
    
    def nominalization(self, concept: str = "") -> str:
        """Возвращает номинализацию"""
        if concept:
            return concept
        return random.choice(self.nominalizations)
    
    def vague_verb(self) -> str:
        """Возвращает неопределенный глагол"""
        return random.choice(self.vague_verbs)
    
    def vague_noun(self) -> str:
        """Возвращает неопределенное имя"""
        return random.choice(self.vague_nouns)
    
    def deletion(self, thought: str = "") -> str:
        """Опущение - незаконченная мысль"""
        start = random.choice(self.deletions)
        if thought:
            return f"{start} {thought}"
        return start
    
    def unspecific_noun(self) -> str:
        """Возвращает неспецифицированное существительное"""
        return random.choice(self.unspecific_nouns)
    
    def milton_phrase(self, topic: str) -> str:
        """Генерирует фразу в стиле Милтон-модели"""
        templates = [
            f"И {self.vague_noun()} может {self.vague_verb()} это {self.unspecific_noun()}",
            f"{self.nominalization()} приходит к {self.vague_noun()} {self.deletion()}",
            f"Когда {self.vague_noun()} {self.vague_verb()}, возникает {self.nominalization()}"
        ]
        return random.choice(templates)


