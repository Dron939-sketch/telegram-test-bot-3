async def show_result(user_id: int, state: FSMContext):
    data = await state.get_data()
    answers: Dict = data.get("answers", {})

    await bot.send_chat_action(user_id, "typing")

    # Отправляем промежуточный экран
    wait_msg = await bot.send_message(
        user_id,
        "⏳ <b>Анализирую ваши стратегии...</b>\n\n"
        "<i>Строю профиль · Ищу паттерны · Формирую траекторию</i>",
    )

    await asyncio.sleep(2)

    parts = format_result(answers)

    try:
        await bot.delete_message(user_id, wait_msg.message_id)
    except Exception:
        pass

    for part in parts:
        await bot.send_message(user_id, part)
        await asyncio.sleep(0.3)

    # Кнопки после результата
    builder = InlineKeyboardBuilder()
    builder.button(text="🔄 Пройти заново", callback_data="go")
    builder.button(text="📋 Матрица поведений", callback_data="matrix")
    builder.adjust(1)

    await bot.send_message(
        user_id,
        "─────────────────────────────────\n"
        "<b>Что дальше?</b>\n\n"
        "Сохраните результат — скриншот или пересылка.\n"
        "Сравните с тем, кого хорошо знаете.",
        reply_markup=builder.as_markup(),
    )

    await state.clear()


@dp.callback_query(F.data == "matrix")
async def cb_matrix(callback: types.CallbackQuery):
    await callback.answer()

    rows = []
    for cat in ("СБ", "ТФ", "УБ", "ЧВ"):
        icon = MATRIX[cat]["icon"]
        label = MATRIX[cat]["label"]
        names = " · ".join(MATRIX[cat][i]["name"] for i in range(1, 7))
        rows.append(f"{icon} <b>{cat} {label}</b>\n<code>{names}</code>")

    text = (
        "📊 <b>МАТРИЦА ПОВЕДЕНИЙ 4×6</b>\n"
        "─────────────────────────────────\n\n"
        + "\n\n".join(rows)
        + "\n\n"
        "<i>Каждый человек — уникальная точка\n"
        f"в пространстве {6**4} возможных профилей.</i>"
    )

    await callback.message.answer(text)


