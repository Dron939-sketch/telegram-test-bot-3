def calculate_profile(raw: Dict[str, str]) -> Dict:
    """
    raw = {"СБ_1_A": "4", "СБ_1_B": "3", ...}
    Возвращает полный профиль с усреднением по триаде.
    """
    # ── 1. Собираем средние по каждой стратегии ──────────────
    strategy_scores: Dict[str, Dict[int, float]] = {
        cat: {} for cat in MATRIX if cat not in ("__all__",)
    }

    for cat in ("СБ", "ТФ", "УБ", "ЧВ"):
        for level in range(1, 7):
            vals = []
            for qtype in ("A", "B", "C"):
                key = f"{cat}_{level}_{qtype}"
                v = raw.get(key)
                if v is not None:
                    try:
                        vals.append(int(v))
                    except ValueError:
                        pass
            strategy_scores[cat][level] = (
                round(statistics.mean(vals), 2) if vals else 3.0
            )

    # ── 2. Первичная и вторичная стратегии ───────────────────
    cocktail: Dict[str, int] = {}
    secondary: Dict[str, Optional[int]] = {}
    stability: Dict[str, float] = {}

    for cat, scores in strategy_scores.items():
        sorted_levels = sorted(scores, key=scores.get, reverse=True)
        primary = sorted_levels[0]
        cocktail[cat] = primary

        # Вторичная — если её средний балл ≥ 60% от первичного
        sec = sorted_levels[1]
        secondary[cat] = (
            sec
            if scores[sec] >= scores[primary] * 0.80
            else None
        )

        # Стабильность (разброс) — насколько чётко выражена доминанта
        vals = list(scores.values())
        avg = statistics.mean(vals)
        std = statistics.stdev(vals) if len(vals) > 1 else 0
        stability[cat] = round(min(std / 2.5 * 100, 100), 1)

    # ── 3. Паттерн внутри категории ──────────────────────────
    patterns: Dict[str, Optional[str]] = {}
    for cat, scores in strategy_scores.items():
        s = scores
        if s[1] >= 4.5 and s[6] >= 4.5:
            patterns[cat] = "нестабильность"   # крайности
        elif sum(s[i] for i in (1, 2, 3)) > sum(s[i] for i in (4, 5, 6)):
            patterns[cat] = "пассивность"
        elif sum(s[i] for i in (4, 5, 6)) > sum(s[i] for i in (1, 2, 3)) + 4:
            patterns[cat] = "активность"
        else:
            patterns[cat] = None

    return {
        "cocktail":   cocktail,
        "secondary":  secondary,
        "stability":  stability,
        "patterns":   patterns,
        "raw_scores": strategy_scores,
    }


