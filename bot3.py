class HypnoOrchestrator:
    """Главный оркестратор, объединяющий все гипнотические модули"""
    
    def __init__(self):
        self.ps = PreSuppositions()
        self.truisms = Truisms()
        self.pl = PseudoLogic()
        self.pc = ParadoxCommands()
        self.es = EmbeddedSuggestions()
        self.hq = HypnoQuestions()
        self.tales = TherapeuticTales()
        self.mm = MiltonModel()
        self.anchoring = Anchoring()
        
        self.technique_map = {
            "сопротивление": ["not_command", "prohibition", "introductory"],
            "недоверие": ["introductory", "fact", "proverb", "trust"],
            "страх": ["tale_fear", "calm", "possibility"],
            "неуверенность": ["tale_growth", "confidence", "rhetorical"],
            "тревога": ["calm", "about_self", "condition"],
            "поиск смысла": ["tale_truth", "insight", "rhetorical"],
            "обучение": ["tale_learning", "curiosity", "alternative"],
            "лень": ["action", "unequal_choice", "cause_effect"],
            "апатия": ["action", "curiosity", "temporal"]
        }
    
    def process_user_input(self, user_id: int, text: str, context: Dict) -> str:
        """Главный метод обработки ввода пользователя"""
        issue = self._detect_issue(text)
        state = self._detect_state(context)
        techniques = self._select_techniques(issue, state)
        response = self._generate_response(techniques, text, context)
        response = self._add_anchors(response, state, user_id)
        return response
    
    def _detect_issue(self, text: str) -> str:
        """Определяет ключевую проблему из текста"""
        keywords = {
            "страх": ["боюсь", "страшно", "боязнь", "пугает"],
            "тревога": ["тревожно", "беспокоюсь", "волнуюсь"],
            "неуверенность": ["не уверен", "сомневаюсь", "не знаю"],
            "апатия": ["все равно", "нет сил", "устал"],
            "сопротивление": ["не хочу", "не буду", "не могу"],
            "недоверие": ["не верю", "сомневаюсь", "вряд ли"],
            "поиск смысла": ["зачем", "почему", "смысл"],
            "обучение": ["научиться", "понять", "разобраться"],
            "лень": ["лень", "неохота", "потом"]
        }
        
        text_lower = text.lower()
        for issue, words in keywords.items():
            for word in words:
                if word in text_lower:
                    return issue
        return "общее"
    
    def _detect_state(self, context: Dict) -> str:
        """Определяет текущее состояние пользователя из контекста"""
        if context.get('confinement_model'):
            model = context['confinement_model']
            if model and hasattr(model, 'key_confinement') and model.key_confinement:
                elem_id = model.key_confinement.get('id')
                state_map = {
                    1: "страх",
                    2: "неуверенность",
                    3: "апатия",
                    4: "сопротивление",
                    5: "поиск смысла",
                    6: "обучение",
                    7: "недоверие",
                    9: "страх"
                }
                return state_map.get(elem_id, "общее")
        return "общее"
    
    def _select_techniques(self, issue: str, state: str) -> List[str]:
        """Выбирает подходящие техники для проблемы и состояния"""
        techniques = self.technique_map.get(issue, [])
        
        state_techniques = {
            "тревога": ["calm", "about_self"],
            "страх": ["tale_fear", "calm"],
            "неуверенность": ["confidence", "rhetorical"],
            "апатия": ["action", "curiosity"],
            "сопротивление": ["not_command", "prohibition"],
            "недоверие": ["introductory", "fact"],
            "поиск смысла": ["tale_truth", "insight"],
            "обучение": ["tale_learning", "curiosity"]
        }
        
        techniques.extend(state_techniques.get(state, []))
        return list(set(techniques))[:3]  # Не больше 3 техник
    
    def _generate_response(self, techniques: List[str], text: str, context: Dict) -> str:
        """Генерирует ответ с использованием выбранных техник"""
        response_parts = []
        
        for technique in techniques:
            if technique.startswith("tale_"):
                tale_type = technique.replace("tale_", "")
                tale = self.tales.get_tale_for_issue(tale_type)
                if tale:
                    response_parts.append(f"📖 {tale['title']}\n\n{tale['text'][:500]}...")
            
            elif technique == "not_command":
                suggestion = self._extract_suggestion(text)
                response_parts.append(self.pc.not_command(suggestion))
            
            elif technique == "prohibition":
                forbidden = self._extract_action(text)
                response_parts.append(self.pc.prohibition(forbidden))
            
            elif technique == "introductory":
                suggestion = self._extract_suggestion(text)
                response_parts.append(self.ps.introductory(suggestion))
            
            elif technique == "fact":
                response_parts.append(self.truisms.fact())
            
            elif technique == "proverb":
                response_parts.append(self.truisms.proverb())
            
            elif technique == "rhetorical":
                suggestion = self._extract_suggestion(text)
                response_parts.append(self.hq.rhetorical(suggestion))
            
            elif technique == "alternative":
                response_parts.append(self.hq.alternative("сделать это сейчас", "подождать"))
            
            elif technique == "unequal_choice":
                response_parts.append(self.hq.unequal_choice("начать сейчас", "откладывать"))
            
            elif technique == "cause_effect":
                response_parts.append(self.pl.cause_effect("это происходит", "ты чувствуешь"))
            
            elif technique == "temporal":
                response_parts.append(self.pl.temporal("ты думаешь об этом", "ты находишь решение"))
            
            elif technique == "about_self":
                response_parts.append(self.truisms.about_self("тебе важно это"))
            
            elif technique == "possibility":
                response_parts.append(self.truisms.possibility("ты можешь это сделать"))
            
            elif technique == "condition":
                response_parts.append(self.truisms.condition("это имеет значение", "ты готов"))
            
            elif technique == "return_question":
                response_parts.append(self.hq.return_question("ты понимаешь это"))
            
            elif technique in ["calm", "confidence", "curiosity", "action", "trust", "insight"]:
                response_parts.append(self.anchoring.get_anchor(technique))
        
        if not response_parts:
            response_parts.append(self.truisms.about_self("я слышу тебя"))
        
        return " ".join(response_parts)
    
    def _add_anchors(self, response: str, state: str, user_id: int) -> str:
        """Добавляет якоря в ответ"""
        emoji = self.anchoring.get_emoji(state)
        anchor = self.anchoring.get_anchor(state, user_id)
        return f"{emoji} {response}\n\n{anchor}"
    
    def _extract_suggestion(self, text: str) -> str:
        """Извлекает внушение из текста пользователя"""
        sentences = text.split('.')
        if sentences:
            return sentences[-1].strip()
        return "довериться процессу"
    
    def _extract_action(self, text: str) -> str:
        """Извлекает действие из текста"""
        return "делать это"


