def get_human_readable_profile(profile: dict, model: ConfinementModel9 = None, user_name: str = "друг") -> str:
    """Возвращает портрет пользователя понятным языком"""
    
    lines = []
    
    # Определяем главный вектор
    strategies = profile.get("strategies", {})
    min_vector = min(strategies.items(), key=lambda x: x[1])
    vector, level_val = min_vector
    
    lines.append(f"🧠 *Каким я тебя вижу, {user_name}:*\n")
    
    # Главный тормоз
    profile_data = LEVEL_PROFILES.get(vector, {}).get(level_val, {})
    lines.append(f"🎯 *Твой главный тормоз*")
    lines.append(f"{profile_data.get('quote', 'Пока не определено')}\n")
    
    # Суперсила
    max_vector = max(strategies.items(), key=lambda x: x[1])
    max_v, max_lvl = max_vector
    max_profile = LEVEL_PROFILES.get(max_v, {}).get(max_lvl, {})
    
    lines.append(f"⚡ *Твоя суперсила*")
    lines.append(f"{max_profile.get('archetype_desc', 'Еще проявится')}\n")
    
    # Откуда это взялось
    lines.append(f"📜 *Откуда это взялось*")
    lines.append(f"{profile_data.get('pain_origin', 'Из твоего опыта')}\n")
    
    # Чем ты платишь
    lines.append(f"💸 *Чем ты платишь*")
    costs = profile_data.get('pain_costs', ['Энергией', 'Временем', 'Возможностями'])
    for cost in costs[:3]:
        lines.append(f"• {cost}")
    lines.append("")
    
    # Конфайнмент если есть
    if model and model.key_confinement:
        elem = model.key_confinement['element']
        lines.append(f"⛓ *Что держит систему*")
        lines.append(f"{elem.description[:100]}\n")
    
    # Петли если есть
    if model and model.loops:
        strongest = max(model.loops, key=lambda x: x['strength'])
        lines.append(f"🔄 *Главная ловушка*")
        lines.append(f"{strongest['description']}")
        lines.append(f"Сила: {strongest['strength']:.1%}\n")
    
    return "\n".join(lines)

