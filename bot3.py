    @staticmethod
    async def create_route(user_id: int, category_id: str, subcategory_id: str) -> dict:
        user = user_data.get(user_id, {})
        scores = {k: round(mean(v), 1) for k, v in user.get("scores", {}).items() if v}
        context = user_contexts.get(user_id)
        mode = context.communication_mode if context else "medium"
        
