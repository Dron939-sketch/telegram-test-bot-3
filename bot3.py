async def ask_question(user_id: int, state: FSMContext, question: Dict):
    """Задаёт вопрос"""
    
    data = await state.get_data()
    last_id = data.get('last_message_id')
    
    if last_id:
        try:
            await bot.delete_message(user_id, last_id)
        except Exception:
            pass
    
    # Определяем прогресс
    current_index = -1
    for i, q in enumerate(QUESTIONS):
        if q["id"] == question["id"]:
            current_index = i
            break
    
    if current_index == -1:
        logger.error(f"❌ Вопрос {question['id']} не найден")
        await bot.send_message(user_id, "❌ Ошибка. Начните заново: /start")
        return
    
    progress = get_progress_bar(current_index + 1, len(QUESTIONS))
    
    # Определяем категорию для эмодзи
    category_emoji = {
        "СБ": "⚔️",
        "ТФ": "🔧", 
        "УБ": "📚",
        "ЧВ": "🤝"
    }
    emoji = category_emoji.get(question.get("category", ""), "📋")
    
    builder = InlineKeyboardBuilder()
    for key, text in question["options"].items():
        builder.button(text=text, callback_data=f"ans_{question['id']}_{key}")
    builder.adjust(1)
    
    # Добавляем информацию о прогрессе по категории
    cat_progress = ""
    if "category" in question:
        cat = question["category"]
        level = question["level"]
        cat_questions = [q for q in QUESTIONS if q.get("category") == cat]
        cat_current = level
        cat_total = len(cat_questions)
        cat_bar = get_progress_bar(cat_current, cat_total, 6)
        cat_progress = f"\n{category_emoji.get(cat, '')} Прогресс по {cat}: {cat_bar}"
    
    sent = await bot.send_message(
        user_id,
        f"{emoji} <b>Вопрос {current_index+1}/{len(QUESTIONS)}</b>\n"
        f"<code>{progress}</code>{cat_progress}\n\n"
        f"{question['text']}",
        reply_markup=builder.as_markup()
    )
    
    await state.update_data(last_message_id=sent.message_id)

