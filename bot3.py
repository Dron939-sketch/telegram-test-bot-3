def clear():
    os.system('cls' if os.name == 'nt' else 'clear')

def sep(char="─", w=62):
    print(char * w)

def header(title):
    sep("═")
    padding = (60 - len(title)) // 2
    print("═" + " " * padding + title + " " * padding + "═")
    sep("═")

def pause(msg="  → Enter: продолжить..."):
    print()
    sep()
    input(msg)

def level(score):
    """Дробный балл → целый уровень"""
    return max(1, min(6, round(score)))

def wrap_text(text, width=60, indent="  "):
    """Форматирует текст с переносом по словам"""
    words = text.split()
    line = indent
    for word in words:
        if len(line) + len(word) + 1 > width:
            print(line)
            line = indent + word + " "
        else:
            line += word + " "
    if line.strip():
        print(line)

