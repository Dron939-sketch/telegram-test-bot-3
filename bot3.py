class ExtendedProfile:
    """
    Расширенный профиль пользователя с конфайнмент-моделью и средой
    """
    
    def __init__(self, user_id: int, user_name: str = ""):
        self.user_id = user_id
        self.user_name = user_name
        self.raw_scores = {}  # сырые баллы по векторам
        self.vector_levels = {}  # уровни (1-6)
        
        self.confinement_model = None
        self.environment_model = None
        self.development_paths = []
        
        self.created_at = datetime.now()
        self.updated_at = datetime.now()
    
    def build_from_test(self, scores: dict):
        """Строит полный профиль из тестовых данных"""
        self.raw_scores = scores
        for k, v in scores.items():
            self.vector_levels[k] = level(v)
        
        # Строим конфайнмент-модель
        self.confinement_model = ConfinementModel({})
        self.confinement_model.build_from_test(scores)
        
        # Строим модель среды
        self.environment_model = EnvironmentModel()
        self.environment_model.assess_from_scores(scores)
        
        # Строим пути развития
        advisor = DevelopmentAdvisor(self.confinement_model, self.environment_model)
        self.development_paths = advisor.generate_paths()
        
        self.updated_at = datetime.now()
        
        return self
    
    def get_profile_summary(self) -> str:
        """Возвращает краткое резюме профиля"""
        if not self.confinement_model or not self.confinement_model.key_confinement:
            return "Профиль еще не построен"
        
        key = self.confinement_model.key_confinement
        weakest_env, env_score = self.environment_model.get_weakest_point()
        
        text = f"🧠 *ВАШ ПРОФИЛЬ*\n\n"
        
        # Векторы
        for vector, lvl in self.vector_levels.items():
            name = VECTORS[vector]['name']
            emoji = VECTORS[vector]['emoji']
            level_name = VECTORS[vector]['levels'][lvl]['name']
            text += f"{emoji} *{name}* — {level_name} ({lvl}/6)\n"
        
        text += f"\n🔍 *КЛЮЧЕВОЕ ОГРАНИЧЕНИЕ*\n"
        text += f"{key['description']}\n\n"
        
        text += f"🌍 *СРЕДА*\n"
        text += f"• Стабильность: {self.environment_model.change_vectors['stability']:.0%}\n"
        text += f"• Поддержка: {self.environment_model.change_vectors['support']:.0%}\n"
        text += f"• Слабое место: {weakest_env[0]}\n\n"
        
        text += f"🔄 *СИСТЕМА*\n"
        text += f"• Стабильность личности: {self.confinement_model.stability:.0%}\n"
        text += f"• Замыкание: {self.confinement_model.closure_score:.0%}\n"
        
        return text
    
    def get_development_paths_text(self) -> str:
        """Возвращает описание путей развития"""
        if not self.development_paths:
            return "Пути развития еще не построены"
        
        text = f"🧭 *ПУТИ РАЗВИТИЯ*\n\n"
        
        for i, path in enumerate(self.development_paths, 1):
            text += f"{i}. *{path.name}*\n"
            text += f"   Сложность: {'🔴' * int(path.difficulty * 5)}{'⚪' * (5 - int(path.difficulty * 5))}\n"
            text += f"   Время: {path.timeframe}\n"
            text += f"   Результат: {path.expected_result}\n"
            
            if path.steps:
                text += f"   Первый шаг: {path.steps[0]['action']}\n"
            
            text += f"\n"
        
        return text
    
    def get_intervention_text(self) -> str:
        """Возвращает текст интервенции для первого шага"""
        if not self.confinement_model or not self.confinement_model.key_confinement:
            return "Сначала завершите тест"
        
        key = self.confinement_model.key_confinement
        user_name = self.user_name or "друг"
        
        text = f"💡 *ПЕРВЫЙ ШАГ ДЛЯ {user_name.upper()}*\n\n"
        text += f"{key['intervention']['exercise']}\n\n"
        text += f"💭 *Вопрос для размышления:*\n"
        text += f"{key['intervention']['question']}\n\n"
        text += f"✨ *Что изменится:*\n"
        text += f"{key['ripple_effect']}"
        
        return text


