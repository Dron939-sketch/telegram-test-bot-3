async def main():
    """Запуск бота"""
    if not TELEGRAM_TOKEN:
        logger.error("TELEGRAM_TOKEN не найден в переменных окружения")
        print("Ошибка: TELEGRAM_TOKEN не найден! Создайте файл .env с TELEGRAM_TOKEN=ваш_токен")
