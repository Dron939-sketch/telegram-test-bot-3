class EmbeddedSuggestions:
    """Выделение ключевых слов в речи"""
    
    markdown_emphasis = {
        "bold": "**{word}**",
        "italic": "_{word}_",
        "code": "`{word}`",
        "spoiler": "||{word}||"
    }
    
    def contextual(self, text: str, suggestion: str, emphasis: str = "bold") -> str:
        """Контекстуальное внушение - выделение слова в тексте"""
        if suggestion in text:
            marked = self.markdown_emphasis[emphasis].format(word=suggestion)
            return text.replace(suggestion, marked)
        return text
    
    def quotes(self, suggestion: str, speaker: str = "") -> str:
        """Внушение в кавычках - цитирование"""
        if speaker:
            return f"{speaker} сказал: «{suggestion}»"
        return f"«{suggestion}»"


