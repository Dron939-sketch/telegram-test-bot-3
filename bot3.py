def level(score):
    """Дробный балл 1..4 → целый уровень 1..6"""
    if score <= 1.49:
        return 1
    elif score <= 2.00:
        return 2
    elif score <= 2.50:
        return 3
    elif score <= 3.00:
        return 4
    elif score <= 3.50:
        return 5
    else:
        return 6

def calculate_progress(current: int, total: int) -> str:
    """Формирует строку прогресса"""
    filled = "█" * current
    empty = "░" * (total - current)
    percent = int((current / total) * 100)
    return f"<b>{filled}{empty} {percent}%</b>"

def generate_unique_callback(prefix: str, user_id: int, question_idx: int, option: str) -> str:
    """Генерирует уникальный callback для защиты от повторных нажатий"""
    timestamp = int(time.time())
    random_salt = random.randint(1000, 9999)
    return f"{prefix}_{question_idx}_{option}_{timestamp}_{random_salt}"

def should_be_ironic(text: str) -> bool:
    """Определяет, стоит ли ответить с иронией"""
    ironic_markers = [
        "очевидно", "разумеется", "конечно", "естественно",
        "неужели", "серьёзно", "правда?", "интересно",
        "ха", "хм", "ну-ну", "ага"
    ]
    return any(marker in text.lower() for marker in ironic_markers)

