async def handle_stage_1_answer(callback: types.CallbackQuery, context: Dict[str, Any]):
    """Обработка ответа ЭТАПА 1"""
    user_id = callback.from_user.id
    data = callback.data
    
    log_debug(f"📥 handle_stage_1_answer: {data}", user_id)
    
    if context.get("processing", False):
        await callback.answer("⏳ Подожди, обрабатываю предыдущий ответ...")
        return STAGE_1
    
    context["processing"] = True
    
    try:
        parts = data.split("_")
        if len(parts) < 3 or parts[0] != "stage1":
            log_debug(f"❌ Неверный формат callback: {data}", user_id)
            return STAGE_1
        
        current = int(parts[1])
        option_id = parts[2]
        
        last_answered = context.get("stage1_last_answered", -1)
        if current <= last_answered:
            log_debug(f"⏭️ Вопрос {current} уже отвечен", user_id)
            await callback.answer("Ты уже ответил на этот вопрос")
            return STAGE_1
        
        question = STAGE_1_QUESTIONS[current]
        selected_option = question["options"].get(option_id)
        
        if not selected_option:
            log_debug(f"❌ Опция {option_id} не найдена", user_id)
            return STAGE_1
        
        scores_add = question["scores"][option_id]
        for axis, score in scores_add.items():
            if axis not in context["scores"]:
                context["scores"][axis] = 0
            context["scores"][axis] += score
            log_debug(f"   +{score} к {axis} (теперь: {context['scores'][axis]})", user_id)
        
        context["all_answers"].append({
            'stage': 1,
            'question_index': current,
            'question': question['text'],
            'answer': selected_option,
            'option': option_id,
            'scores': scores_add
        })
        
        context["stage1_last_answered"] = current
        context["stage1_current"] = current + 1
        
        return await ask_stage_1_question(callback, context)
        
    except Exception as e:
        log_debug(f"❌ Ошибка: {e}", user_id)
        return await ask_stage_1_question(callback, context)
    finally:
        context["processing"] = False

