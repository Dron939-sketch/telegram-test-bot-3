def build_trajectory(cocktail: Dict[str, int]) -> Dict:
    for arch in ARCHETYPES:
        if arch["cond"](cocktail):
            traj = TRAJECTORIES.get(arch["trajectory"], TRAJECTORIES["default"])
            return {"archetype": arch, "trajectory": traj}
    return {"archetype": None, "trajectory": TRAJECTORIES["default"]}


