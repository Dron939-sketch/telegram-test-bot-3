async def handle_message(message: types.Message):
    """Обработчик текстовых сообщений"""
    user_id = message.from_user.id
    user = user_data.get(user_id)
    
    if not user:
        await message.answer("Начни с /start", reply_markup=InlineKeyboardMarkup(inline_keyboard=[
            [InlineKeyboardButton(text="🏠 Меню", callback_data="back_to_start")]
        ]))
        return
    
    # Если ждем свободный вопрос
    if user.get("awaiting_question"):
        await handle_free_question(message, user)
        return
    
    # Если тест не пройден
    if user.get("conversation_state") != RESULTS and not user.get("final_profile"):
        await message.answer(
            "Сначала пройди тест. Нажми /start",
            reply_markup=InlineKeyboardMarkup(inline_keyboard=[
                [InlineKeyboardButton(text="🚀 Пройти тест", callback_data="start_test")]
            ])
        )
        return
    
    # Иначе обрабатываем как вопрос
    context = user
    profile = context.get("final_profile", {})
    model_data = context.get("confinement_model")
    model = ConfinementModel9.from_dict(model_data) if model_data else None
    
    await message.reply("🤔 *Думаю над ответом...*", parse_mode="Markdown")
    
    mode = "medium"
    if user_id in user_contexts:
        mode = user_contexts[user_id].communication_mode
    
    mode_prompt = COMMUNICATION_MODES.get(mode, COMMUNICATION_MODES["medium"])["prompt"]
    
    profile_text = f"Стратегии: СБ-{profile.get('strategies', {}).get('СБ', 3)}/6, ТФ-{profile.get('strategies', {}).get('ТФ', 3)}/6, УБ-{profile.get('strategies', {}).get('УБ', 3)}/6, ЧВ-{profile.get('strategies', {}).get('ЧВ', 3)}/6"
    
    confinement_text = ""
    if model and model.key_confinement:
        elem = model.key_confinement['element']
        confinement_text = f"Ключевое ограничение: {elem.name}"
    
    prompt = f"""Вопрос: {message.text}

ПРОФИЛЬ ПОЛЬЗОВАТЕЛЯ:
{profile_text}
{confinement_text}

СТИЛЬ: {mode_prompt}

Дай короткий, практичный ответ, 2-4 предложения, с учетом профиля. Отвечай от имени Шнура."""
    
    response = await call_deepseek(prompt, max_tokens=300)
    
    if not response:
        response = f"Слушай, я вижу твой профиль. С такими вводными я бы посоветовал начать с малого."
    
    keyboard = InlineKeyboardMarkup(inline_keyboard=[
        [InlineKeyboardButton(text="❓ Ещё вопрос", callback_data="show_help")],
        [InlineKeyboardButton(text="🧠 К портрету", callback_data="show_results")]
    ])
    
    await message.reply(
        f"🧠 *Ответ Шнура*\n\n{response}",
        reply_markup=keyboard,
        parse_mode="Markdown"
    )
    
    if YANDEX_API_KEY:
        audio_data = await text_to_speech(response, mode)
        if audio_data:
            audio_file = BufferedInputFile(audio_data, filename="response.ogg")
            await message.reply_voice(
                audio_file,
                caption="🎙 *Голосовой ответ от Шнура*",
                parse_mode="Markdown"
            )

