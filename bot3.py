def get_progress_bar(current: int, total: int, length: int = 10) -> str:
    """Прогресс-бар"""
    filled = int((current / total) * length)
    return "█" * filled + "░" * (length - filled)

def calculate_profile(data: Dict) -> Dict:
    """
    Рассчитывает профиль (коктейль из 4 чисел)
    Для каждой категории находим уровень с максимальным баллом
    """
    
    # Группируем ответы по категориям
    categories = {
        "СБ": [f"sb_q{i}" for i in range(1, 7)],
        "ТФ": [f"tf_q{i}" for i in range(1, 7)],
        "УБ": [f"ub_q{i}" for i in range(1, 7)],
        "ЧВ": [f"chv_q{i}" for i in range(1, 7)]
    }
    
    result = {}
    raw_scores = {}
    confidence = {}  # Уверенность в выборе (насколько доминирует максимальный балл)
    
    for cat, questions in categories.items():
        # Собираем баллы для каждого уровня в этой категории
        level_scores = {}
        for i, q in enumerate(questions, 1):
            val = data.get(q)
            if val is None:
                logger.warning(f"⚠️ Отсутствует ответ на вопрос {q}, использую 3")
                level_scores[i] = 3
            else:
                try:
                    level_scores[i] = int(val)
                except ValueError:
                    logger.warning(f"⚠️ Неверное значение {val} для {q}, использую 3")
                    level_scores[i] = 3
        
        # Находим уровень с максимальным баллом
        dominant_level = max(level_scores, key=level_scores.get)
        max_score = level_scores[dominant_level]
        
        # Вычисляем уверенность (насколько max больше среднего)
        avg_score = sum(level_scores.values()) / len(level_scores)
        confidence[cat] = round((max_score - avg_score) / 5 * 100, 1)  # в процентах
        
        result[cat] = dominant_level
        raw_scores[cat] = level_scores
    
    return {
        "cocktail": result,  # Например: {"СБ": 4, "ТФ": 2, "УБ": 5, "ЧВ": 3}
        "raw_scores": raw_scores,
        "confidence": confidence,
        "matrix": MATRIX
    }

