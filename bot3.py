def run_test() -> dict:
    clear()
    header("МАТРИЦА ПОВЕДЕНИЙ 4×6")
    print("""
  Тест определяет ваш поведенческий профиль
  по четырём ключевым векторам:

  СБ — как реагируете на угрозу
  ТФ — как добываете ресурсы
  УБ — как отвечаете на непонятное
  ЧВ — как строите отношения с людьми

  12 вопросов. Нет правильных ответов.
  Выбирайте то что ближе всего к реальности
  а не то каким хотите быть.
    """)
    input("  Нажмите Enter чтобы начать...")

    raw_scores = {k: [] for k in VECTORS}

    q_num = 0
    total_q = sum(len(v) for v in QUESTIONS.values())

    for vector_key, questions in QUESTIONS.items():
        for question in questions:
            q_num += 1
            clear()

            vec = VECTORS[vector_key]
            print(f"  Вопрос {q_num} из {total_q}  |  "
                  f"{vector_key}: {vec['name']}")
            sep()
            print(f"\n  {question['text']}\n")

            for idx, (score, text) in enumerate(question["options"], 1):
                print(f"  {idx}.  {text}")

            while True:
                try:
                    ans = int(input("\n  Ваш выбор (1–6): ").strip())
                    if 1 <= ans <= 6:
                        raw_scores[vector_key].append(
                            question["options"][ans - 1][0]
                        )
                        break
                    print("  Введите число от 1 до 6")
                except ValueError:
                    print("  Введите число от 1 до 6")

    return {k: round(mean(v), 1) for k, v in raw_scores.items()}

def show_profile(scores: dict):
    clear()
    header("ВАШ ПРОФИЛЬ")
    print()

    for key, score in scores.items():
        vec = VECTORS[key]
        lvl = level(score)
        info = vec["levels"][lvl]

        filled = "█" * lvl
        empty  = "░" * (6 - lvl)
        bar = filled + empty

        print(f"  {key}  [{bar}]  {score:.1f} / 6")
        print(f"       {vec['name']}")
        print(f"       Уровень {lvl}: {info['name']}  —  {info['action']}")
        print(f"       {info['desc']}")
        print()

    sb = level(scores["СБ"])
    tf = level(scores["ТФ"])
    ub = level(scores["УБ"])
    cv = level(scores["ЧВ"])

    sep()
    print(f"\n  Профиль:  СБ-{sb}  ТФ-{tf}  УБ-{ub}  ЧВ-{cv}\n")

def show_patterns(scores: dict):
    clear()
    header("ПОЧЕМУ В ВАШЕЙ ЖИЗНИ ПРОИСХОДИТ ТО ЧТО ПРОИСХОДИТ")

    found_any = False

    for key in ["ТФ", "СБ", "УБ", "ЧВ"]:
        lvl = level(scores[key])
        patterns = LIFE_PATTERNS.get(key, {})

        if lvl in patterns:
            found_any = True
            vec = VECTORS[key]
            print(f"\n  ▶  {key} — {vec['name']}  (уровень {lvl}: "
                  f"{vec['levels'][lvl]['name']})")
            sep("─")
            wrap_text(patterns[lvl], width=58, indent="  ")

    if not found_any:
        print("\n  Ваши уровни достаточно высоки.")
        print("  Выраженных деструктивных паттернов не обнаружено.")
        print("  Фокус: интеграция и масштабирование.")

def show_correlations(scores: dict):
    clear()
    header("СВЯЗИ МЕЖДУ ВЕКТОРАМИ — ОТКУДА БЕРЁТСЯ ПРОИСХОДЯЩЕЕ")

    active = [c for c in CORRELATIONS if c["condition"](scores)]

    if not active:
        print("\n  Значимых проблемных корреляций не обнаружено.")
        print("  Ваши векторы относительно согласованы между собой.")
    else:
        for c in active:
            print(f"\n  ⚡  {c['title']}")
            sep("─")
            wrap_text(c["explanation"], width=58, indent="  ")
            print(f"\n  ➜  {c['solution']}")

def get_priority_order(scores: dict) -> list:
    """Определяет порядок приоритетов для развития"""
    tf = level(scores["ТФ"])

    if tf <= 2:
        rest = sorted(
            [(k, v) for k, v in scores.items() if k != "ТФ"],
            key=lambda x: x[1]
        )
        return ["ТФ"] + [r[0] for r in rest]
    else:
        return [k for k, _ in sorted(scores.items(), key=lambda x: x[1])]

def show_standard_recommendations(scores: dict):
    """Стандартные рекомендации (без AI)"""
    clear()
    header("РЕКОМЕНДАЦИИ — ЧТО МЕНЯТЬ И В КАКОМ ПОРЯДКЕ")

    order = get_priority_order(scores)
    bottleneck = order[0]

    print(f"\n  🎯  УЗКОЕ МЕСТО: {bottleneck} — {VECTORS[bottleneck]['name']}")
    print(f"      Уровень {level(scores[bottleneck])}: "
          f"{VECTORS[bottleneck]['levels'][level(scores[bottleneck])]['name']}")
    print()
    print("  Это то что ограничивает рост остальных векторов.")
    print("  Менять его первым — наиболее эффективный путь.")

    icons = ["🔴", "🟡", "🟢", "⚪"]
    labels = [
        "НАЧАТЬ ЗДЕСЬ — приоритет 1",
        "СЛЕДУЮЩИЙ ШАГ — приоритет 2", 
        "РАЗВИВАТЬ — приоритет 3",
        "ПОДДЕРЖИВАТЬ — уже неплохо",
    ]

    print()
    sep()

    for i, key in enumerate(order):
        lvl   = level(scores[key])
        vec   = VECTORS[key]
        icon  = icons[i] if i < len(icons) else "⚪"
        label = labels[i] if i < len(labels) else "ПОДДЕРЖИВАТЬ"
        recs  = RECOMMENDATIONS.get(key, {}).get(lvl, [])

        print(f"\n  {icon}  {key} — {vec['name']}  "
              f"(уровень {lvl}: {vec['levels'][lvl]['name']})")
        print(f"      {label}")
        sep("·")

        if recs:
            for r in recs:
                wrap_text(r, width=58, indent="      • ")
        else:
            print("      Ваш уровень здесь высокий — поддерживайте.")

def show_summary(scores: dict):
    """Итоговый вывод"""
    clear()
    header("ИТОГ И ГЛАВНЫЙ ВЫВОД")

    order      = get_priority_order(scores)
    bottleneck = order[0]
    tf  = level(scores["ТФ"])
    sb  = level(scores["СБ"])
    ub  = level(scores["УБ"])
    cv  = level(scores["ЧВ"])

    print(f"""
  Ваш профиль: СБ-{sb} ТФ-{tf} УБ-{ub} ЧВ-{cv} """)
    sep()

    print("\n  ЧТО СЕЙЧАС ПРОИСХОДИТ В ВАШЕЙ ЖИЗНИ:\n")

    if tf <= 2 and sb <= 2:
        print("  Вы в режиме ВЫЖИВАНИЯ.")
        print("  Энергия уходит на базовую безопасность.")
        print("  Развитие, отношения, смыслы — вторичны.")
        print("  Один выход: создать минимальный ресурсный буфер.")
    elif ub >= 5 and tf <= 3:
        print("  Вы многое понимаете — но мало можете изменить.")
        print("  Разрыв между пониманием и возможностями создаёт напряжение.")
        print("  Знание должно конвертироваться в ресурс.")
    elif cv >= 4 and sb <= 2 and tf <= 3:
        print("  Вы тянетесь к людям — но не защищены внутри отношений.")
        print("  Паттерн: нравитесь людям, зависите от них, не можете отстоять себя.")
    elif min(tf, sb, ub, cv) >= 4:
        print("  Все векторы на достаточном уровне.")
        print("  Вы в фазе ИНТЕГРАЦИИ и МАСШТАБИРОВАНИЯ.")
    else:
        print(f"  Ваш ограничивающий фактор: {bottleneck}")
        print(f"  Начните с {bottleneck}. Остальное подтянется следом.")

    print()
    sep()
    print("\n  Матрица описывает не то кто вы есть.")
    print("  Она описывает то как вы реагируете сейчас.")
    print("  Реакции меняются. Контекст меняется.")
    print("  Профиль — не приговор. Это точка отсчёта.")

