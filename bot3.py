def determine_dominant_dilts(answers: list) -> str:
    """Определяет доминирующий уровень Дилтса"""
    if not answers:
        return "BEHAVIOR"
    
    counts = {
        "ENVIRONMENT": 0,
        "BEHAVIOR": 0,
        "CAPABILITIES": 0,
        "BELIEFS": 0,
        "IDENTITY": 0,
        "MISSION": 0
    }
    
    for answer in answers:
        counts[answer] += 1
    
    return max(counts, key=counts.get)

